/*
let - valores que podem ser substituídos (variáveis).
const - valores que não podem ser substituídos e devem ser iniciados com algum valor.
*/

let fruta;

console.log (fruta)

fruta = 'banana';

console.log (fruta)

fruta = 'maçã';

console.log (fruta)

const animal = 'cachorro';

console.log (animal)
//Diferente da let, o const não aceita a mudança do valor definido e apresenta erro.//